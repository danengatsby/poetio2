import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
const root = new URL('../', import.meta.url);
const sources = ['poetio-balloons.png', 'blue-hour.webp', 'poem-tuesday.webp', 'poem-rain.webp', 'poem-repair.webp', 'poem-spring.webp'];
const manifest = {};
await mkdir(new URL('public/optimized/', root), { recursive: true });
for (const file of sources) {
  const source = await readFile(new URL(`public/assets/${file}`, root));
  const logo = file.startsWith('poetio-balloons');
  const variants = [];
  for (const width of logo ? [480, 800, 1120, 1600, 2048] : [320, 480, 640, 960, 1280]) {
    const { data, info } = await sharp(source).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: logo ? 90 : 82, effort: 5 }).toBuffer({ resolveWithObject: true });
    if (variants.some(v => v.width === info.width)) continue;
    const hash = createHash('sha256').update(data).digest('hex').slice(0, 16);
    const path = `/optimized/${file.replace(/\.[^.]+$/, '')}-${info.width}-${hash}.webp`;
    await writeFile(fileURLToPath(new URL(`public${path}`, root)), data);
    variants.push({ src: path, width: info.width, height: info.height });
  }
  manifest[`/assets/${file}`] = variants;
}
await writeFile(new URL('lib/generated-images.ts', root), '// Generated by npm run build:images. Keep the source assets unchanged.\nexport const generatedImages: Record<string, { src: string; width: number; height: number }[]> = ' + JSON.stringify(manifest, null, 2) + ';\n');
console.log(`Optimized ${sources.length} static images into responsive WebP variants.`);
